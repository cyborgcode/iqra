// Builds the app's Quran data from the verbatim Tanzil files in data/tanzil/:
//   public/quran/001.json … 114.json  – one file per surah, loaded on demand
//   src/data/surahs.ts                – surah names and ayah counts for the picker
// The text is copied as-is: no character of any ayah is added, removed or changed.
//
// usage: node scripts/build-quran-data.mjs [--check]
//   --check  exit with an error if the committed files differ from a fresh build

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT, readDivisions, readMetadata, readQuranTxt, readQuranXml } from "./quran-source.mjs";

const TOTAL_AYAHS = 6236;

export function buildOutputs() {
  const quran = readQuranXml();
  const meta = readMetadata();
  const txt = readQuranTxt();

  if (quran.surahs.length !== 114 || meta.surahs.length !== 114) {
    throw new Error(`Expected 114 surahs, got ${quran.surahs.length} (text) / ${meta.surahs.length} (metadata)`);
  }
  let total = 0;
  for (const [i, surah] of quran.surahs.entries()) {
    const info = meta.surahs[i];
    if (surah.number !== i + 1 || info.number !== i + 1) throw new Error(`Surah order mismatch at ${i + 1}`);
    if (surah.ayahs.length !== info.ayahs) {
      throw new Error(`Surah ${surah.number}: ${surah.ayahs.length} ayahs in text, ${info.ayahs} in metadata`);
    }
    if (surah.name !== info.name) throw new Error(`Surah ${surah.number}: name mismatch`);
    const expectBismillah = surah.number !== 1 && surah.number !== 9;
    if (expectBismillah !== (surah.bismillah !== null)) {
      throw new Error(`Surah ${surah.number}: unexpected basmala presence`);
    }
    // Independent cross-check: Tanzil's .txt export prefixes ayah 1 with the basmala.
    surah.ayahs.forEach((text, a) => {
      const expected = a === 0 && surah.bismillah ? `${surah.bismillah} ${text}` : text;
      if (txt.get(`${surah.number}:${a + 1}`) !== expected) {
        throw new Error(`Surah ${surah.number}:${a + 1} differs between the XML and TXT exports`);
      }
    });
    total += surah.ayahs.length;
  }
  if (total !== TOTAL_AYAHS || txt.size !== TOTAL_AYAHS) {
    throw new Error(`Expected ${TOTAL_AYAHS} ayahs, got ${total} (XML) / ${txt.size} (TXT)`);
  }

  const files = new Map();
  for (const surah of quran.surahs) {
    const json = {
      copyright: quran.copyright,
      source: {
        name: "Tanzil Project",
        url: "https://tanzil.net",
        text: "Tanzil Quran Text (Uthmani, Version 1.1) with pause marks and sajdah signs, used verbatim",
      },
      surah: surah.number,
      bismillah: surah.bismillah,
      ayahs: surah.ayahs,
    };
    files.set(`public/quran/${String(surah.number).padStart(3, "0")}.json`, `${JSON.stringify(json, null, 2)}\n`);
  }

  const lines = meta.surahs.map(
    (s) =>
      `  { number: ${s.number}, name: ${JSON.stringify(s.name)}, transliteration: ${JSON.stringify(
        s.transliteration,
      )}, translation: ${JSON.stringify(s.translation)}, ayahs: ${s.ayahs}, revelation: ${JSON.stringify(s.revelation)} },`,
  );
  const ts = `// Generated by scripts/build-quran-data.mjs from data/tanzil/quran-data.xml. Do not edit.
// Surah metadata: Tanzil Project (https://tanzil.net), ${meta.copyright}, license: ${meta.license}.

export interface SurahInfo {
  number: number;
  /** Arabic name, as published by Tanzil. */
  name: string;
  /** English transliteration, as published by Tanzil. */
  transliteration: string;
  /** English meaning of the name, as published by Tanzil. */
  translation: string;
  ayahs: number;
  revelation: "Meccan" | "Medinan";
}

export const SURAHS: readonly SurahInfo[] = [
${lines.join("\n")}
];
`;
  files.set("src/data/surahs.ts", ts);

  const div = readDivisions();
  if (div.pages.length !== 604 || div.juzs.length !== 30 || div.hizbQuarters.length !== 240 || div.sajdas.length !== 15) {
    throw new Error("Unexpected number of pages, juz, hizb quarters or sajdas in quran-data.xml");
  }
  const list = (starts) => starts.map(([s, a]) => `[${s},${a}]`).join(",");
  const book = `// Generated by scripts/build-quran-data.mjs from data/tanzil/quran-data.xml. Do not edit.
// Divisions of the Mushaf: Tanzil Project (https://tanzil.net), ${meta.copyright}, license: ${meta.license}.

/** A position in the Quran: [surah, ayah]. */
export type AyahStart = readonly [number, number];

/** First ayah of each of the 604 pages of the Madani Mushaf. */
export const PAGE_STARTS: readonly AyahStart[] = [${list(div.pages)}];

/** First ayah of each of the 30 juz. */
export const JUZ_STARTS: readonly AyahStart[] = [${list(div.juzs)}];

/** First ayah of each of the 240 hizb quarters (four per hizb, two hizbs per juz). */
export const HIZB_QUARTER_STARTS: readonly AyahStart[] = [${list(div.hizbQuarters)}];

/** The 15 ayahs with a sajdah. */
export const SAJDAS: readonly (readonly [number, number, "recommended" | "obligatory"])[] = [${div.sajdas
    .map(([s, a, type]) => `[${s},${a},${JSON.stringify(type)}]`)
    .join(",")}];
`;
  files.set("src/data/book.ts", book);
  return files;
}

function main() {
  const check = process.argv.includes("--check");
  const files = buildOutputs();
  let stale = 0;
  for (const [rel, content] of files) {
    const target = path.join(ROOT, rel);
    const current = existsSync(target) ? readFileSync(target, "utf8") : null;
    if (current === content) continue;
    stale++;
    if (!check) {
      mkdirSync(path.dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
  if (check && stale) {
    console.error(`${stale} generated file(s) are out of date. Run: npm run data`);
    process.exit(1);
  }
  console.log(check ? "Quran data is up to date." : `Wrote ${stale} file(s); ${files.size - stale} unchanged.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
